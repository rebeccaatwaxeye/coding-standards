// Core installer logic for the Nocturna coding standards.
//
// Byte-format contract shared with standards/agents/install.sh and the
// nocturna-standards cargo CLI — all three must produce identical files so
// any tool's `status` agrees with any other tool's `install`:
//   - stamp line: `<!-- nocturna-standards v<version> -->`
//   - slice paths in AGENTS.md rewritten `rules/X.md` -> `agents/rules/X.md`
//   - standards.json: version + installed languages
//   - .cursorrules: generated header + core + slices concatenated
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const LANGS = ['typescript', 'php', 'rust', 'python']

const sha256 = (content) => createHash('sha256').update(content).digest('hex')

/** The standards version, parsed from the canonical document header. */
export function sourceVersion(assetsDir) {
	const doc = readFileSync(join(assetsDir, 'CODING_STANDARDS.md'), 'utf8')
	const match = doc.match(/^> \*\*Version:\*\* (\S+)/m)
	if (!match) throw new Error('could not parse version from CODING_STANDARDS.md')
	return match[1]
}

/** Core AGENTS.md as it should exist in the target: stamp + rewritten slice paths. */
export function expectedCore(assetsDir, version) {
	const core = readFileSync(join(assetsDir, 'AGENTS.md'), 'utf8')
	const rewritten = core.replace(/`rules\/([a-z]+)\.md`/g, '`agents/rules/$1.md`')
	return `<!-- nocturna-standards v${version} -->\n${rewritten}`
}

/** CODING_STANDARDS.md as it should exist in the target: stamp + canonical content. */
export function expectedStandardsDoc(assetsDir, version) {
	const doc = readFileSync(join(assetsDir, 'CODING_STANDARDS.md'), 'utf8')
	return `<!-- nocturna-standards v${version} -->\n${doc}`
}

/** Generated .cursorrules: header + installed core + selected slices. */
export function expectedCursorrules(assetsDir, version, langs) {
	const lines = [
		'# Nocturna Coding Standards',
		'#',
		`# GENERATED by nocturna-standards v${version} — do not edit directly.`,
		'# Edit AGENTS.md or rules/*.md in the source repo and re-run the installer.',
		`# Installed languages: ${langs.join(' ')}`,
		'',
		expectedCore(assetsDir, version)
	]
	let out = lines.join('\n')
	for (const lang of langs) {
		const slice = readFileSync(join(assetsDir, 'rules', `${lang}.md`), 'utf8')
		out += `\n---\n\n${slice}`
	}
	return out
}

function manifestContent(version, langs) {
	const langsJson = langs.map((l) => `"${l}"`).join(', ')
	return `{\n  "version": "${version}",\n  "languages": [${langsJson}]\n}\n`
}

export function validateLangs(langs) {
	for (const lang of langs) {
		if (!LANGS.includes(lang)) {
			throw new Error(`unknown language '${lang}'. Available: ${LANGS.join(' ')}`)
		}
	}
}

/** Install the standards into targetDir. Returns report lines (mirrors install.sh). */
export function install(targetDir, langs, assetsDir) {
	validateLangs(langs)
	if (!existsSync(targetDir)) {
		throw new Error(`target directory does not exist: ${targetDir}`)
	}
	const version = sourceVersion(assetsDir)
	mkdirSync(join(targetDir, 'agents', 'rules'), { recursive: true })

	const lines = []
	writeFileSync(join(targetDir, 'AGENTS.md'), expectedCore(assetsDir, version))
	lines.push(`  AGENTS.md -> ${join(targetDir, 'AGENTS.md')} (standards v${version})`)

	writeFileSync(join(targetDir, 'CODING_STANDARDS.md'), expectedStandardsDoc(assetsDir, version))
	lines.push(
		`  CODING_STANDARDS.md -> ${join(targetDir, 'CODING_STANDARDS.md')} (standards v${version})`
	)

	for (const lang of langs) {
		const slice = readFileSync(join(assetsDir, 'rules', `${lang}.md`), 'utf8')
		writeFileSync(join(targetDir, 'agents', 'rules', `${lang}.md`), slice)
		lines.push(`  rules/${lang}.md -> ${join(targetDir, 'agents', 'rules', `${lang}.md`)}`)
	}

	writeFileSync(join(targetDir, 'agents', 'standards.json'), manifestContent(version, langs))
	lines.push(`  agents/standards.json (v${version}: ${langs.join(' ')})`)

	writeFileSync(join(targetDir, '.cursorrules'), expectedCursorrules(assetsDir, version, langs))
	lines.push(`  .cursorrules -> ${join(targetDir, '.cursorrules')} (core + ${langs.join(' ')})`)

	return lines
}

function readManifest(targetDir) {
	const manifestPath = join(targetDir, 'agents', 'standards.json')
	if (!existsSync(manifestPath)) return null
	const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
	return { version: manifest.version, langs: manifest.languages ?? [] }
}

/**
 * Check an installed repo for drift. Returns { ok, lines } — ok is false when
 * an update is needed (mirrors install.sh --status semantics and output).
 */
export function status(targetDir, assetsDir) {
	const version = sourceVersion(assetsDir)
	const manifest = readManifest(targetDir)
	if (!manifest) {
		return {
			ok: false,
			lines: [
				'NOT INSTALLED — no agents/standards.json found',
				`Install with: nocturna-standards install ${targetDir} [lang ...]`
			]
		}
	}

	const lines = []
	let drift = false

	if (manifest.version === version) {
		lines.push(`standards: v${version} — UP TO DATE`)
	} else {
		lines.push(`standards: v${manifest.version} installed, v${version} available — OUTDATED`)
		drift = true
	}

	const compareFile = (label, path, expected) => {
		if (!existsSync(path)) {
			lines.push(`  ${label}: MISSING`)
			drift = true
		} else if (sha256(readFileSync(path, 'utf8')) !== sha256(expected)) {
			lines.push(`  ${label}: MODIFIED (differs from source v${version})`)
			drift = true
		} else {
			lines.push(`  ${label}: OK`)
		}
	}

	for (const lang of manifest.langs) {
		const slicePath = join(assetsDir, 'rules', `${lang}.md`)
		if (!existsSync(slicePath)) {
			lines.push(`  ${lang}: UNKNOWN (not in source v${version})`)
			drift = true
			continue
		}
		compareFile(
			lang,
			join(targetDir, 'agents', 'rules', `${lang}.md`),
			readFileSync(slicePath, 'utf8')
		)
	}

	compareFile('core AGENTS.md', join(targetDir, 'AGENTS.md'), expectedCore(assetsDir, version))
	compareFile(
		'CODING_STANDARDS.md',
		join(targetDir, 'CODING_STANDARDS.md'),
		expectedStandardsDoc(assetsDir, version)
	)

	compareFile(
		'.cursorrules',
		join(targetDir, '.cursorrules'),
		expectedCursorrules(assetsDir, version, manifest.langs)
	)

	if (drift) {
		lines.push(
			'',
			`Update needed: nocturna-standards install ${targetDir} ${manifest.langs.join(' ')}`
		)
	}
	return { ok: !drift, lines }
}
