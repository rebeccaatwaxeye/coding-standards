import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterEach, beforeAll, describe, expect, it } from 'vitest'
import { syncAssets } from '../scripts/sync-assets.mjs'
import {
	expectedCore,
	expectedStandardsDoc,
	install,
	LANGS,
	sourceVersion,
	status
} from './install.mjs'

const assetsDir = fileURLToPath(new URL('../assets/', import.meta.url))

let target
beforeAll(() => syncAssets())
afterEach(() => {
	if (target) rmSync(target, { recursive: true, force: true })
	target = undefined
})

const freshTarget = () => {
	target = mkdtempSync(join(tmpdir(), 'nocturna-standards-test-'))
	return target
}

describe('sourceVersion', () => {
	it('parses a semver version from the canonical document', () => {
		expect(sourceVersion(assetsDir)).toMatch(/^\d+\.\d+\.\d+$/)
	})
})

describe('install', () => {
	it('writes all files for all languages by default', () => {
		const dir = freshTarget()
		install(dir, LANGS, assetsDir)
		for (const file of [
			'AGENTS.md',
			'CODING_STANDARDS.md',
			'.cursorrules',
			'agents/standards.json',
			...LANGS.map((l) => `agents/rules/${l}.md`)
		]) {
			expect(existsSync(join(dir, file)), file).toBe(true)
		}
	})

	it('stamps AGENTS.md and rewrites slice paths', () => {
		const dir = freshTarget()
		install(dir, ['typescript'], assetsDir)
		const core = readFileSync(join(dir, 'AGENTS.md'), 'utf8')
		expect(core.startsWith(`<!-- nocturna-standards v${sourceVersion(assetsDir)} -->`)).toBe(true)
		expect(core).toContain('`agents/rules/typescript.md`')
		expect(core).not.toContain('`rules/typescript.md`')
	})

	it('stamps the standards document snapshot', () => {
		const dir = freshTarget()
		install(dir, ['rust'], assetsDir)
		expect(readFileSync(join(dir, 'CODING_STANDARDS.md'), 'utf8')).toBe(
			expectedStandardsDoc(assetsDir, sourceVersion(assetsDir))
		)
	})

	it('writes a manifest with version and languages', () => {
		const dir = freshTarget()
		install(dir, ['typescript', 'python'], assetsDir)
		const manifest = JSON.parse(readFileSync(join(dir, 'agents', 'standards.json'), 'utf8'))
		expect(manifest.version).toBe(sourceVersion(assetsDir))
		expect(manifest.languages).toEqual(['typescript', 'python'])
	})

	it('generates .cursorrules with core and selected slices', () => {
		const dir = freshTarget()
		install(dir, ['php'], assetsDir)
		const cursorrules = readFileSync(join(dir, '.cursorrules'), 'utf8')
		expect(cursorrules).toContain('# GENERATED by nocturna-standards')
		expect(cursorrules).toContain('# Coding Standards — Agent Reference')
		expect(cursorrules).toContain('# PHP (Laravel)')
		expect(cursorrules).not.toContain('# Rust\n')
	})

	it('rejects unknown languages', () => {
		const dir = freshTarget()
		expect(() => install(dir, ['cobol'], assetsDir)).toThrow(/unknown language 'cobol'/)
	})

	it('rejects a target directory that does not exist', () => {
		const dir = join(freshTarget(), 'missing')
		expect(() => install(dir, ['rust'], assetsDir)).toThrow(/target directory does not exist/)
	})
})

describe('status', () => {
	it('reports NOT INSTALLED for an empty directory', () => {
		const dir = freshTarget()
		const report = status(dir, assetsDir)
		expect(report.ok).toBe(false)
		expect(report.lines[0]).toContain('NOT INSTALLED')
	})

	it('is clean immediately after install', () => {
		const dir = freshTarget()
		install(dir, LANGS, assetsDir)
		const report = status(dir, assetsDir)
		expect(report.lines.join('\n')).toContain('UP TO DATE')
		expect(report.ok).toBe(true)
	})

	it('detects a modified slice', () => {
		const dir = freshTarget()
		install(dir, ['typescript'], assetsDir)
		writeFileSync(
			join(dir, 'agents', 'rules', 'typescript.md'),
			`${readFileSync(join(dir, 'agents', 'rules', 'typescript.md'), 'utf8')}\nhand edit\n`
		)
		const report = status(dir, assetsDir)
		expect(report.ok).toBe(false)
		expect(report.lines.join('\n')).toContain('typescript: MODIFIED')
	})

	it('detects a missing standards document', () => {
		const dir = freshTarget()
		install(dir, ['rust'], assetsDir)
		rmSync(join(dir, 'CODING_STANDARDS.md'))
		const report = status(dir, assetsDir)
		expect(report.ok).toBe(false)
		expect(report.lines.join('\n')).toContain('CODING_STANDARDS.md: MISSING')
	})

	it('detects an outdated install and names the update command', () => {
		const dir = freshTarget()
		install(dir, ['python'], assetsDir)
		writeFileSync(
			join(dir, 'agents', 'standards.json'),
			'{ "version": "0.0.1", "languages": ["python"] }\n'
		)
		const report = status(dir, assetsDir)
		expect(report.ok).toBe(false)
		expect(report.lines[0]).toContain('OUTDATED')
		expect(report.lines.join('\n')).toContain('Update needed: nocturna-standards install')
	})

	it('detects a hand-edited core AGENTS.md', () => {
		const dir = freshTarget()
		install(dir, ['php'], assetsDir)
		writeFileSync(join(dir, 'AGENTS.md'), `${expectedCore(assetsDir, '0.0.0')}`)
		const report = status(dir, assetsDir)
		expect(report.ok).toBe(false)
		expect(report.lines.join('\n')).toContain('core AGENTS.md: MODIFIED')
	})
})
