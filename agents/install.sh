#!/usr/bin/env bash
#
# Install Nocturna coding standards into a repository.
#
# Usage:
#   ./install.sh <target-dir> [lang ...]     install or update
#   ./install.sh --status <target-dir>       report installed version and drift
#
# Examples:
#   ./install.sh ../my-api typescript
#   ./install.sh ../my-api typescript python
#   ./install.sh .                        # install all languages
#   ./install.sh --status ../my-api       # non-zero exit if an update is needed
#
# What it does:
#   1. Copies AGENTS.md to <target>/AGENTS.md, stamped with the standards version
#   2. Copies the selected language slices to <target>/agents/rules/
#   3. Writes <target>/agents/standards.json recording version and languages
#   4. Generates <target>/.cursorrules as core + selected slices concatenated
#
# .cursorrules is generated rather than committed so it can never drift
# from AGENTS.md. Re-run this script to update an existing install;
# `--status` tells you whether one is needed.
#
# The standards version lives in VERSION next to this script. Bump it
# whenever AGENTS.md or any slice changes, so consumer repos can detect
# stale installs with --status.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ALL_LANGS=(typescript php rust python)
VERSION="$(cat "$SCRIPT_DIR/VERSION")"
MANIFEST_REL="agents/standards.json"

# --- Helpers ---

hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

hash_string() {
  local tmp
  tmp="$(mktemp)"
  printf '%s' "$1" > "$tmp"
  hash_file "$tmp"
  rm -f "$tmp"
}

# Core AGENTS.md as it should exist in the target: version stamp + rewritten paths.
expected_core() {
  echo "<!-- nocturna-standards v$VERSION -->"
  sed -E 's#`rules/([a-z]+)\.md`#`agents/rules/\1.md`#g' "$SCRIPT_DIR/AGENTS.md"
}

# --- Parse arguments ---

MODE="install"
if [[ "${1:-}" == "--status" ]]; then
  MODE="status"
  shift
fi

TARGET="${1:-}"
if [[ -z "$TARGET" ]]; then
  echo "Usage: $0 [--status] <target-dir> [lang ...]" >&2
  echo "Available languages: ${ALL_LANGS[*]}" >&2
  exit 1
fi
shift || true

# --- Validate ---

if [[ ! -d "$TARGET" ]]; then
  echo "Error: target directory does not exist: $TARGET" >&2
  exit 1
fi

# --- Status mode ---

if [[ "$MODE" == "status" ]]; then
  MANIFEST="$TARGET/$MANIFEST_REL"
  if [[ ! -f "$MANIFEST" ]]; then
    echo "NOT INSTALLED — no $MANIFEST_REL in $TARGET"
    echo "Install with: install.sh $TARGET [lang ...]"
    exit 1
  fi

  INSTALLED_VERSION="$(sed -n 's/.*"version": "\([^"]*\)".*/\1/p' "$MANIFEST")"
  langs_raw="$(sed -n 's/^  "languages": \[\(.*\)\]$/\1/p' "$MANIFEST")"
  langs_raw="${langs_raw//\"/}"
  IFS=',' read -ra LANGS_INSTALLED <<< "$langs_raw"
  for i in "${!LANGS_INSTALLED[@]}"; do
    LANGS_INSTALLED[$i]="$(echo "${LANGS_INSTALLED[$i]}" | tr -d ' ')"
  done

  DRIFT=0

  if [[ "$INSTALLED_VERSION" == "$VERSION" ]]; then
    echo "standards: v$VERSION — UP TO DATE"
  else
    echo "standards: v$INSTALLED_VERSION installed, v$VERSION available — OUTDATED"
    DRIFT=1
  fi

  for lang in "${LANGS_INSTALLED[@]}"; do
    lang="$(echo "$lang" | tr -d ' ')"
    [[ -z "$lang" ]] && continue
    FILE="$TARGET/agents/rules/$lang.md"
    SRC="$SCRIPT_DIR/rules/$lang.md"
    if [[ ! -f "$FILE" ]]; then
      echo "  $lang: MISSING"
      DRIFT=1
    elif [[ "$(hash_file "$FILE")" != "$(hash_file "$SRC")" ]]; then
      echo "  $lang: MODIFIED (differs from source v$VERSION)"
      DRIFT=1
    else
      echo "  $lang: OK"
    fi
  done

  CORE="$TARGET/AGENTS.md"
  if [[ ! -f "$CORE" ]]; then
    echo "  core AGENTS.md: MISSING"
    DRIFT=1
  elif [[ "$(hash_string "$(expected_core)")" != "$(hash_string "$(cat "$CORE")")" ]]; then
    echo "  core AGENTS.md: MODIFIED (differs from source v$VERSION)"
    DRIFT=1
  else
    echo "  core AGENTS.md: OK"
  fi

  if [[ -f "$TARGET/.cursorrules" ]]; then
    TMP_EXPECTED="$(mktemp)"
    {
      echo "# Nocturna Coding Standards"
      echo "#"
      echo "# GENERATED by coding-standards/agents/install.sh v$VERSION — do not edit directly."
      echo "# Edit AGENTS.md or rules/*.md in the source repo and re-run the installer."
      echo "# Installed languages: ${LANGS_INSTALLED[*]}"
      echo
      cat "$TARGET/AGENTS.md"
      for lang in "${LANGS_INSTALLED[@]}"; do
        lang="$(echo "$lang" | tr -d ' ')"
        [[ -z "$lang" ]] && continue
        echo
        echo "---"
        echo
        cat "$SCRIPT_DIR/rules/$lang.md"
      done
    } > "$TMP_EXPECTED"
    if [[ "$(hash_file "$TMP_EXPECTED")" != "$(hash_file "$TARGET/.cursorrules")" ]]; then
      echo "  .cursorrules: STALE (regenerate with install.sh)"
      DRIFT=1
    else
      echo "  .cursorrules: OK"
    fi
    rm -f "$TMP_EXPECTED"
  fi

  if [[ "$DRIFT" -ne 0 ]]; then
    echo
    echo "Update needed: install.sh $TARGET ${LANGS_INSTALLED[*]}"
    exit 1
  fi
  exit 0
fi

# --- Install mode ---

LANGS=("$@")
if [[ ${#LANGS[@]} -eq 0 ]]; then
  LANGS=("${ALL_LANGS[@]}")
fi

for lang in "${LANGS[@]}"; do
  if [[ ! -f "$SCRIPT_DIR/rules/$lang.md" ]]; then
    echo "Error: unknown language '$lang'. Available: ${ALL_LANGS[*]}" >&2
    exit 1
  fi
done

mkdir -p "$TARGET/agents/rules"

# --- Install AGENTS.md ---
# Rewrite slice paths: rules/X.md -> agents/rules/X.md because AGENTS.md
# moves from agents/ to the target root.

expected_core > "$TARGET/AGENTS.md"
echo "  AGENTS.md -> $TARGET/AGENTS.md (standards v$VERSION)"

# --- Install language slices ---

for lang in "${LANGS[@]}"; do
  cp "$SCRIPT_DIR/rules/$lang.md" "$TARGET/agents/rules/$lang.md"
  echo "  rules/$lang.md -> $TARGET/agents/rules/$lang.md"
done

# --- Write the version manifest ---

langs_json="\"${LANGS[0]}\""
if [[ ${#LANGS[@]} -gt 1 ]]; then
  for lang in "${LANGS[@]:1}"; do
    langs_json+=", \"$lang\""
  done
fi

{
  echo '{'
  echo "  \"version\": \"$VERSION\","
  echo "  \"languages\": [$langs_json]"
  echo '}'
} > "$TARGET/$MANIFEST_REL"
echo "  $MANIFEST_REL (v$VERSION: ${LANGS[*]})"

# --- Generate .cursorrules ---
# Cursor reads a single root file, so concatenate core + selected slices.

{
  echo "# Nocturna Coding Standards"
  echo "#"
  echo "# GENERATED by coding-standards/agents/install.sh v$VERSION — do not edit directly."
  echo "# Edit AGENTS.md or rules/*.md in the source repo and re-run the installer."
  echo "# Installed languages: ${LANGS[*]}"
  echo
  cat "$TARGET/AGENTS.md"
  for lang in "${LANGS[@]}"; do
    echo
    echo "---"
    echo
    cat "$SCRIPT_DIR/rules/$lang.md"
  done
} > "$TARGET/.cursorrules"

echo "  .cursorrules -> $TARGET/.cursorrules (core + ${LANGS[*]})"

# --- Summary ---

echo
echo "Installed Nocturna coding standards v$VERSION into: $TARGET"
echo
echo "  Languages: ${LANGS[*]}"
echo
echo "Commit AGENTS.md, agents/, and .cursorrules with your project."
echo "Check for updates later with: install.sh --status $TARGET"
